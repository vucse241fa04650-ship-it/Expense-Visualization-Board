import { getCategoryTotals, getMonthlyExpenses, getTotalSpent, formatDate, formatMonthLabel } from './expenseUtils'
import { CATEGORIES } from './categories'

// jsPDF's built-in fonts have no rupee glyph (it would print as garbage), so the PDF uses "Rs."
const rs = (n) => 'Rs. ' + Number(n).toLocaleString('en-IN', { maximumFractionDigits: 2 })

/**
 * Downloads "expense-report-YYYY-MM.pdf".
 * Page 1: title, summary table, category breakdown. Page 2: day-wise transactions.
 * jsPDF is loaded on demand so it stays out of the main bundle.
 */
export async function exportMonthlyPDF(expenses, month, budget) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
  ])

  const monthExpenses = getMonthlyExpenses(expenses, month).sort(
    (a, b) => a.date.localeCompare(b.date) || a.id - b.id,
  )
  const total = getTotalSpent(monthExpenses)
  const totals = getCategoryTotals(monthExpenses)
  const hasBudget = budget > 0
  const head = { fillColor: [79, 70, 229] }
  const footer = 'Generated by Personal Expense Tracker'

  const doc = new jsPDF()
  doc.setFontSize(18)
  doc.text(`Expense Report — ${formatMonthLabel(month)}`, 14, 20)
  doc.setFontSize(10)
  doc.setTextColor(100)
  doc.text(`Generated: ${new Date().toLocaleString('en-IN')}`, 14, 27)
  doc.setTextColor(0)

  autoTable(doc, {
    startY: 34,
    head: [['Total Spent', 'Budget', 'Remaining', '% Used']],
    body: [[
      rs(total),
      hasBudget ? rs(budget) : 'Not set',
      hasBudget ? rs(budget - total) : '-',
      hasBudget ? `${Math.round((total / budget) * 100)}%` : '-',
    ]],
    headStyles: head,
  })

  autoTable(doc, {
    startY: doc.lastAutoTable.finalY + 12,
    head: [['Category', 'Amount', '% of Total']],
    body: CATEGORIES.filter((c) => totals[c] > 0).map((c) => [
      c,
      rs(totals[c]),
      `${((totals[c] / total) * 100).toFixed(1)}%`,
    ]),
    headStyles: head,
  })

  doc.addPage()
  doc.setFontSize(14)
  doc.text('Day-wise expenses', 14, 20)
  autoTable(doc, {
    startY: 26,
    head: [['Date', 'Description', 'Category', 'Amount']],
    body: monthExpenses.length
      ? monthExpenses.map((e) => [formatDate(e.date), e.description, e.category, rs(e.amount)])
      : [['No expenses recorded this month', '', '', '']],
    headStyles: head,
    columnStyles: { 3: { halign: 'right' } },
  })

  const pages = doc.getNumberOfPages()
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i)
    doc.setFontSize(9)
    doc.setTextColor(120)
    doc.text(footer, 14, doc.internal.pageSize.getHeight() - 10)
  }

  doc.save(`expense-report-${month}.pdf`)
}
